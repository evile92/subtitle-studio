type SyncMode = 'youtube' | 'anchors' | 'fps' | 'reference';

interface LoadedFile {
  name: string;
  parsed: ParsedTimedSubtitle;
}

interface SyncComputation {
  cues: TimedCue[];
  transform?: LinearTimeTransform;
  method?: 'exact_copy' | 'linear_anchor' | 'cadence_correlation';
  confidence?: number;
  clampedCount: number;
  error?: string;
}

export interface SubtitleSyncToolProps {
  onSendToTranslator?: (payload: { fileName: string; content: string }) => void;
}

